/* =========================================================
   NPC取得
========================================================= */

export function getNPC(id) {
  return NPCS[id] ?? null;
}



/* =========================================================
   NPC存在確認
========================================================= */

export function hasNPC(id) {
  return Boolean(NPCS[id]);
}



/* =========================================================
   NPC一覧取得
========================================================= */

export function getAllNPCs() {
  return Object.values(NPCS);
}



/* =========================================================
   名前取得
========================================================= */

export function getNPCName(id) {

  const npc = getNPC(id);

  if (!npc) {
    return '';
  }

  return npc.name;
}



/* =========================================================
   画像取得

   現在は画像ファイル名未設定なので null。
   GitHubへ画像を置いたら npc.js の image を変更する。
========================================================= */

export function getNPCImage(id) {

  const npc = getNPC(id);

  if (!npc) {
    return null;
  }

  return npc.image;
}